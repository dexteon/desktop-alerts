#!/usr/bin/env python3
"""Install desktop-alerts package."""
import argparse
import os
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
PACKAGE_DIR = HERE / "desktop_alerts"
SCRIPTS_DIR = HERE / "scripts"

REQUIREMENTS = ["pystray", "winotify", "pillow", "pywin32"]


def run(cmd, check=True, **kwargs):
    print(f"> {' '.join(cmd)}")
    return subprocess.run(cmd, check=check, **kwargs)


def install_deps(python: str):
    """Install Python dependencies."""
    print("Installing dependencies...")
    run([python, "-m", "pip", "install", "--upgrade", "pip"])
    run([python, "-m", "pip", "install", *REQUIREMENTS])


def register_protocol(python: str, identity: str):
    """Register the desktop-alerts: URI protocol handler."""
    print("Registering URI protocol handler...")
    script = HERE.parent / "desktop_alerts" / "desktop_alerts.py"
    run([python, str(script), "test"])  # This calls register_protocol()


def create_shortcut(python: str, identity: str, data_dir: Path):
    """Create a shortcut in the Startup folder for auto-start."""
    startup = Path(os.environ["APPDATA"]) / "Microsoft" / "Windows" / "Start Menu" / "Programs" / "Startup"
    startup.mkdir(parents=True, exist_ok=True)

    pyw = Path(python).with_name("pythonw.exe")
    if not pyw.exists():
        pyw = Path(python)

    shortcut_path = startup / f"{identity} Alerts.lnk"
    target = str(pyw)
    script = HERE.parent / "desktop_alerts" / "desktop_alerts.py"
    args = f'"{script}" run'
    work_dir = str(HERE.parent / "desktop_alerts")

    # Create shortcut via PowerShell
    ps_cmd = f"""
    $WshShell = New-Object -comObject WScript.Shell
    $Shortcut = $WshShell.CreateShortcut("{shortcut_path}")
    $Shortcut.TargetPath = "{target}"
    $Shortcut.Arguments = "{args}"
    $Shortcut.WorkingDirectory = "{work_dir}"
    $Shortcut.Description = "{identity} desktop alerts tray app"
    $Shortcut.Save()
    """
    run(["powershell", "-NoProfile", "-Command", ps_cmd])
    print(f"Created startup shortcut: {shortcut_path}")


def write_env_file(identity: str, data_dir: Path, portal_url: str, python: str):
    """Write a .env file with the configuration."""
    env_path = HERE / ".env"
    hermes_exe = Path(os.environ.get("LOCALAPPDATA", r"C:\Users\Public")) / "hermes" / "bin" / "hermes.exe"

    content = f"""# Desktop Alerts Configuration
# Generated by install.py on {__import__('datetime').datetime.now().isoformat()}

DESKTOP_ALERTS_IDENTITY={identity}
DESKTOP_ALERTS_DATA_DIR={data_dir}
DESKTOP_ALERTS_PORTAL_URL={portal_url}
DESKTOP_ALERTS_HERMES_EXE={hermes_exe}
DESKTOP_ALERTS_POLL_S=60
DESKTOP_ALERTS_STALE_MIN=90
DESKTOP_ALERTS_SYS_HOURS=72
DESKTOP_ALERTS_INBOX_KEEP_H=48
DESKTOP_ALERTS_CLAUDE_CMD=claude
"""
    env_path.write_text(content, encoding="utf-8")
    print(f"Wrote config to {env_path}")


def main():
    ap = argparse.ArgumentParser(description="Install desktop-alerts")
    ap.add_argument("--identity", default="DesktopAlerts", help="App name (default: DesktopAlerts)")
    ap.add_argument("--data-dir", default="", help="Data directory (default: %LOCALAPPDATA%\\DesktopAlerts)")
    ap.add_argument("--portal-url", default="", help="Health page URL for 'Health page' button")
    ap.add_argument("--python", default=sys.executable, help="Python executable to use")
    ap.add_argument("--no-deps", action="store_true", help="Skip dependency installation")
    ap.add_argument("--no-startup", action="store_true", help="Don't create startup shortcut")
    ap.add_argument("--no-protocol", action="store_true", help="Don't register URI protocol")
    args = ap.parse_args()

    identity = args.identity
    data_dir = Path(args.data_dir) if args.data_dir else Path(os.environ.get("LOCALAPPDATA", r"C:\Users\Public")) / "DesktopAlerts"
    portal_url = args.portal_url
    python = args.python

    print(f"Installing {identity} alerts...")
    print(f"  Data dir: {data_dir}")
    print(f"  Portal URL: {portal_url or '(none)'}")
    print(f"  Python: {python}")

    data_dir.mkdir(parents=True, exist_ok=True)

    if not args.no_deps:
        install_deps(python)

    write_env_file(identity, data_dir, portal_url, python)

    if not args.no_protocol:
        # Load .env into current process
        from dotenv import load_dotenv
        load_dotenv(HERE / ".env", override=True)
        register_protocol(python, identity)

    if not args.no_startup:
        create_shortcut(python, identity, data_dir)

    print("\n✓ Installation complete!")
    print(f"\nTo run manually:")
    print(f"  {python} {PACKAGE_DIR / 'desktop_alerts.py'} run")
    print(f"\nTo test:")
    print(f"  {python} {PACKAGE_DIR / 'desktop_alerts.py'} test")
    print(f"\nConfig file: {HERE / '.env'}")
    print(f"Data directory: {data_dir}")
    print(f"\nThe tray app will start automatically on next sign-in.")


if __name__ == "__main__":
    try:
        main()
    except subprocess.CalledProcessError as e:
        print(f"\n✗ Installation failed: {e}")
        sys.exit(1)
    except Exception as e:
        print(f"\n✗ Unexpected error: {e}")
        sys.exit(1)